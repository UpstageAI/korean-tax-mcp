def _night(it, y, daily):
    amt = _num(it.get("연금액"))
    m, g = NIGHT[y]
    occ = OCCUPATION[max(k for k in OCCUPATION if k <= y)]
    basis = f"{_L} 제12조제3호더목, {_D} 제17조제1항({NIGHT_BASIS[y]})·제2항"
    mine_daily = bool(it.get("광산일용")) or bool(daily)
    if it.get("생산직직종") is False:
        return _row("야간근로수당", "과세", f"영 제17조제1항 각 호 직종이 아님 — {y}년 범위: {occ}", basis)
    if it.get("생산직직종") is None:
        return _row("야간근로수당", "확인 필요", f"{y}년 대상 직종: {occ}. 월정액급여 {_won(m)} 이하·직전 과세기간 총급여 {_won(g)} 이하, 연장·야간·휴일근로수당 연 240만원(광산·일용근로자는 전액) — 생산직직종 입력", basis,
                    기준=f"월정액급여 {_won(m)} 이하, 직전 과세기간 총급여 {_won(g)} 이하")
    if mine_daily:
        r = _row("야간근로수당", "비과세", "광산근로자·일용근로자는 연장·야간·휴일근로 급여 총액 비과세"
                 + (" — 일용근로자는 월정액급여·직전 총급여와 관계없음(서면-2015-소득지원-1440)" if daily or it.get("광산일용") == "일용" else ""), basis + ", 서면-2015-소득지원-1440")
        if amt is not None:
            r.update({"비과세(연)": amt, "과세(연)": 0})
        return r
    mw, pg = _num(it.get("월정액급여")), _num(it.get("직전연도총급여"))
    miss = [n for n, v in (("월정액급여", mw), ("직전연도총급여", pg)) if v is None]
    if miss:
        return _row("야간근로수당", "확인 필요", f"{y}년 기준 — 월정액급여 {_won(m)} 이하이고 직전 과세기간 총급여 {_won(g)} 이하. 입력: {', '.join(miss)}", basis,
                    기준=f"월정액급여 {_won(m)} 이하, 직전 과세기간 총급여 {_won(g)} 이하")
    if mw > m or pg > g:
        why = []
        if mw > m: why.append(f"월정액급여 {_won(mw)} > {_won(m)}")
        if pg > g: why.append(f"직전 과세기간 총급여 {_won(pg)} > {_won(g)}")
        return _row("야간근로수당", "과세", " · ".join(why) + " — 월정액급여는 해당 월 기준이라 기준을 넘는 달의 수당은 과세", basis, **({"비과세(연)": 0, "과세(연)": amt} if amt is not None else {}))
    if amt is None:
        return _row("야간근로수당", "확인 필요", "요건 충족 — 연장·야간·휴일근로로 통상임금에 더해 받는 급여 연 240만원 이하 비과세. 연금액 입력 시 과세분 계산", basis, 한도="연 2,400,000원")
    s = _split(amt, 2_400_000, "연")
    return _row("야간근로수당", "일부 과세" if s["과세(연)"] else "비과세", f"월정액급여 {_won(mw)}·직전 총급여 {_won(pg)} 기준 충족 — 연 {_won(amt)} 중 240만원까지 비과세", basis, 한도="연 2,400,000원", **s)


