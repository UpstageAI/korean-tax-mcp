"""전원합의체 판결로 변경된 대법원 판결 표시 — 검색·본문 결과의 문서번호에 붙이는 작은 고정 표. Claude 작성(2026-11-15).

대법원 2025. 9. 18. 선고 2021두59908 전원합의체 판결(국내 미등록 특허의 특허기술이 국내에서 사용되면 그 사용료는 국내원천소득)이
판결문에서 '이 판결의 견해와 배치되는 범위 내에서 모두 변경'한다고 열거한 8건만 넣는다(판결문 전문에서 확인).
열거되지 않은 하급심·심판례는 표시하지 않는다 — 같은 취지였는지는 본문으로 따로 확인해야 한다.
"""
import re

EN_BANC_2021DU59908 = "변경됨 — 대법원 2025.9.18. 2021두59908 전원합의체"

# (선고 연도 사건번호 연도 4자리, 사건 부호, 번호): 선고일
OVERRULED = {
    ("1991", "누", "6887"): "1992.5.12.",
    ("2005", "두", "8641"): "2007.9.7.",
    ("2012", "두", "18356"): "2014.11.27.",
    ("2013", "두", "9670"): "2014.12.11.",
    ("2016", "두", "42883"): "2018.12.27.",
    ("2018", "두", "36592"): "2022.2.10.",
    ("2019", "두", "50946"): "2022.2.10.",
    ("2019", "두", "47100"): "2022.2.24.",
}
_NO = re.compile(r"(?<!\d)(\d{4}|\d{2})\s*-?\s*(누|두)\s*-?\s*(\d{3,6})(?!\d)")


def key(doc_no):
    """'대법원-2012-두-18356'·'대법원 2014. 11. 27. 선고 2012두18356 판결'·'대법원-91-누-6887' → ('2012', '두', '18356'). 대법원 사건이 아니면 None."""
    s = doc_no or ""
    if "대법원" not in s: return None
    m = _NO.search(s)
    if not m: return None
    y = m.group(1)
    if len(y) == 2: y = ("19" if int(y) >= 50 else "20") + y
    return (y, m.group(2), m.group(3))


def flag(doc_no):
    """변경된 판결이면 표시 문구, 아니면 None."""
    k = key(doc_no)
    if k in OVERRULED:
        return f"{EN_BANC_2021DU59908}(이 판결은 대법원 {OVERRULED[k]} 선고 — 전원합의체 판결의 견해와 배치되는 범위에서 변경)"
    return None


def mark(item):
    """결과 dict에 '판례 변경' 키를 붙임(해당할 때만). 같은 dict를 돌려준다."""
    f = flag(item.get("문서번호", "")) if isinstance(item, dict) else None
    if f: item["판례 변경"] = f
    return item
