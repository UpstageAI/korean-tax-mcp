def _date(v, name, 문제):
    if v is None:
        return None
    try:
        return D.fromisoformat(str(v))
    except ValueError:
        문제.append(f"{name}={v!r} — YYYY-MM-DD")
        return None


def _add_months(d, n):
    y, m = divmod(d.month - 1 + n, 12)
    y, m = d.year + y, m + 1
    for day in (d.day, 30, 29, 28):
        try:
            return D(y, m, day)
        except ValueError:
            continue


def months(start, end):
    """start~end(양끝 포함) 개월 수 — 1개월 미만은 1개월(법 제22조제4항제1호)."""
    if end < start:
        return 0
    stop = end + _dt.timedelta(days=1)
    n = (stop.year - start.year) * 12 + stop.month - start.month
    while n > 0 and _add_months(start, n) > stop:
        n -= 1
    if _add_months(start, n) < stop:
        n += 1
    return n


