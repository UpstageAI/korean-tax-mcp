    if agent_contract_authority:
        J.append(_j("종속대리인", "국내사업장 있음", "국내에서 계약을 체결할 권한을 가지고 반복적으로 행사하는 자를 둠"
                    + (" — 2019 시행본부터 계약 유형(명의 계약·자산 소유권 이전·사용권 허락·용역제공 계약) 확인" if p != "2018 이전" else ""),
                    f"{law} {art}제3항" + ("제1호" if p != "2018 이전" else "")))
    if agent_principal_role:
        if p == "2018 이전":
            J.append(_j("종속대리인(중요한 역할)", "확인 필요", "계약 체결 과정의 중요한 역할만 하는 자는 2019.1.1. 시행본부터 명시 — 2018년까지는 '이에 준하는 자'(대통령령) 해당 여부를 따로 확인",
                        f"{law} {art}제3항(2018 시행본까지)"))
        else:
            J.append(_j("종속대리인(중요한 역할)", "국내사업장 있음", "체결 권한이 없어도 계약 체결 과정에서 중요한 역할을 반복 수행(본인이 중요사항을 바꾸지 않고 체결하는 경우로 한정)",
                        f"{law} {art}제3항제2호"))
            check.append("본인이 계약의 중요사항을 변경하지 않고 체결하는지(제3항제2호 괄호)")
    if agent_types:
        dec, who, _ = _decree(taxpayer, year)
        old, new = _agent2(year, taxpayer)
        obj = "외국법인을" if taxpayer == "외국법인" else "비거주자를"
        basis = f"{law} {art}제3항, {dec}"
        plain = [t for t in agent_types if t not in (AGENT_SPECIFIC, AGENT_RELATED)]
        if plain:
            J.append(_j("대통령령으로 정하는 자", "국내사업장 있음", f"{', '.join(plain)} — {dec}의 자(제1호·제3호, 2016~2026 문언 같음)", basis))
        if AGENT_SPECIFIC in agent_types:
            if year <= 2025:
                J.append(_j("대통령령으로 정하는 자(독립대리인)", "국내사업장 있음", f"독립적 지위의 대리인이 {old} — {year}년 시행본 제2호", basis + ("제2호" if taxpayer == "비거주자" else "제2호·제2항")))
            else:
                J.append(_j("대통령령으로 정하는 자(독립대리인)", "확인 필요",
                            f"'주로 {_decree(taxpayer)[2]}만을 위하여'는 2026.2.26.까지의 문언 — 2026.2.27.부터는 '{new}'인지 확인(부칙에 적용례 없음)", basis + "제2호"))
                check.append(f"대리인이 전적으로 또는 거의 전적으로 특수관계(국제조세조정에 관한 법률 제2조제1항제3호)가 있는 {obj} 위하여 행위하는지 — 2026.2.27. 이후분")
        if AGENT_RELATED in agent_types:
            if year <= 2025:
                J.append(_j("대통령령으로 정하는 자(독립대리인)", "확인 필요",
                            f"{year}년 시행본 제2호는 '{old}' — 특수관계가 있다는 것만으로는 부족하고 주로 그 {who}만을 위하여 행위하는지 확인"
                            "('특수관계 … 전적으로 또는 거의 전적으로'는 2026.2.27. 개정 문언)", basis + "제2호"))
                check.append(f"대리인이 주로 {_decree(taxpayer)[2]}만을 위하여 계약체결 등 중요한 부분의 행위를 하는지({dec}제2호)"
                             + (" — 외국법인에는 과점주주·특수관계인 포함(제2항)" if taxpayer == "외국법인" else ""))
            else:
                J.append(_j("대통령령으로 정하는 자(독립대리인)", "국내사업장 있음",
                            f"독립적 지위의 대리인이 {new} — 2026.2.27. 시행 문언. 2026.2.26.까지는 종전 문언('{old}') 해당 여부로 판단", basis + "제2호"))
                check.append("대리인의 행위가 '전적으로 또는 거의 전적으로' 그 특수관계인을 위한 것인지, 2026.2.26. 이전분은 종전 문언에 해당하는지")
    if agent_contract_authority is False and agent_principal_role is False and not agent_types:
        J.append(_j("종속대리인", "해당 없음", "계약 체결 권한 반복 행사자·중요한 역할 수행자·준하는 자가 없다고 입력", f"{law} {art}제3항"))
    if agent_contract_authority is None and agent_principal_role is None and not agent_types:
        check.append("국내에서 계약을 체결하거나 체결 과정에서 중요한 역할을 반복하는 대리인이 있는지(agent_contract_authority·agent_principal_role)")

    verdicts = [x["판정"] for x in J]
    if "국내사업장 있음" in verdicts:
        concl = "국내법상 국내사업장 있음(입력 사실 기준)"
    elif "확인 필요" in verdicts or check:
        concl = "확인 필요 — 아래 확인 필요 사항을 채우면 다시 판정"
    else:
        concl = "국내법상 국내사업장 없음(입력 사실 기준)"
    treaty = {"안내": "조세조약이 있으면 조약의 고정사업장 조항(건설 기간, 종속대리인·독립대리인, 예비적·보조적 활동)을 함께 봐야 함 — 국내법과 기간·요건이 다를 수 있고 조약이 우선할 수 있음",
              "조약에서 확인할 조항": ["건설·설치·조립 공사와 관련 감독활동이 고정사업장이 되는 기간(조약마다 6·9·12개월 등 — 국내법 6개월과 다를 수 있음)",
                                  "용역 고정사업장(서비스 PE) 조항이 있는지 — 없으면 국내법의 용역 제공 장소(제2항제5호, 12개월 중 6개월 초과)에 해당해도 그것만으로는 조약상 고정사업장이 되지 않고, 조약의 고정된 사업장소(일반 정의)·건설 조항으로 따로 판단",
                                  "종속대리인·독립대리인, 예비적·보조적 활동의 조약 문언"],
              "다음 단계": f"tax_treaty(country='{treaty_country or '상대국'}', keyword='고정사업장')"}
    if treaty_country and any(x["판정"] == "국내사업장 있음" and ("용역" in x["항목"] or "건설" in x["항목"]) for x in J):
        treaty["주의"] = ("국내법상 용역 제공 장소·건설현장으로 '국내사업장 있음'이 나왔음 — 조약의 기간 요건과 용역 고정사업장 조항으로 다시 판단해야 함"
                        "(조약이 정한 기간에 못 미치거나 용역 고정사업장 조항이 없으면 조약상 고정사업장이 아닐 수 있음)")
    if "국내사업장 있음" in concl:
        calc = [{"도구": "계산 MCP corporate_tax" if taxpayer == "외국법인" else "계산 MCP income_tax", "용도": "국내사업장에 귀속되는 소득의 신고·납부 세액"}]
        if taxpayer == "외국법인":
            calc.append({"도구": "계산 MCP branch_profits_tax", "용도": "지점세(조약이 허용하는 경우)"})
    elif "국내사업장 없음" in concl:
        calc = [{"도구": "계산 MCP nonresident_withholding", "용도": "국내사업장이 없으면 국내원천소득을 지급할 때 원천징수(소득 종류·조약 세율)"}]
    else:
        calc = [{"도구": "계산 MCP nonresident_withholding", "용도": "국내사업장이 없다고 정해지면 — 국내원천소득 원천징수"},
                {"도구": "계산 MCP branch_profits_tax" if taxpayer == "외국법인" else "계산 MCP income_tax", "용도": "국내사업장이 있다고 정해지면 — " + ("지점세" if taxpayer == "외국법인" else "종합소득 신고")}]
    return {"기준 연도": year, "적용 시행본": f"{year}년 연말 시행본 기준({p})", "적용 기준": APPLICATION[taxpayer], "납세자": taxpayer, "결론": concl, "판정": J, "계산 다음 단계": calc,
            "확인 필요": check, "요소": _elements(year, taxpayer), "조세조약": treaty,
            "다음 단계": [f"law_article(law_name='{law}', article='{art}', as_of='{year}1231')로 원문 확인",
                       f"article_addenda(law_name='{law}', article='{art}')로 개정 적용례 확인",
                       treaty["다음 단계"]],
            "해석·판례": RULINGS, "해석·판례 안내": RULINGS_NOTE, "한계": LIMITS, "확인 시행본": VERIFIED}
