"""지방세 안내 — 지방세 해석·심판례는 국세법령정보시스템에 거의 없음을 알리는 문구.

지방세 불복은 행정심판법 적용 배제(지방세기본법 제98조제1항)·심판청구 필요적 전치(제3항)라
결정례는 조세심판원(법제처 특별행정심판재결례)에 있다.
"""
import re

_LOCAL_TAX_RE = re.compile(
    r"지방세|취득세|등록면허세|등록세|재산세|지방소득세|주민세|자동차세|지역자원시설세|지방교육세"
)


def local_tax_note(query: str, results: list[dict]) -> str | None:
    """query 또는 results의 세목에 지방세 낱말이 있으면 안내 문구 반환, 아니면 None."""
    hay = query or ""
    for r in results:
        tax = (r.get("세목") or "")
        if tax:
            hay += " " + tax
    if _LOCAL_TAX_RE.search(hay):
        return (
            "지방세(취득세·재산세 등) 해석·심판례는 국세법령정보시스템에 거의 없음"
            "(옛 등록세·감사원 심사 일부) — "
            "지방세 불복은 행정심판법 적용 배제(지방세기본법 제98조제1항)·"
            "심판청구 필요적 전치(제3항)이므로 "
            "'조세심판원 결정례' 항목(법제처 특별행정심판재결례)을 먼저 보고, "
            "행정안전부 유권해석은 지방세법령정보시스템에서 확인"
        )
    return None
