def _housing(d, f):
    base = f"{_V} 제26조제1항제12호, {_R} 제41조"
    new = d >= D2024_7     # 2024.7.1. 이후 공급분: 면적 한도 제1항 후단 → 제2항, 겸용주택 제2항 → 제3항(대통령령 제34270호 부칙 제5조)
    lim_h, mix_h = ("제2항", "제3항") if new else ("제1항 후단", "제2항")
    out = []
    res = f.get("residential")
    if res is False:
        return [_j("주택 임대", "과세", "상시주거용이 아님(사업을 위한 주거용 포함) — 주택 임대 면세 대상 아님", base + "제1항")]
    if res is None:
        out.append(_j("주택 임대", "확인 필요", "상시주거용(사업을 위한 주거용 제외)인지(residential)로 갈림", base + "제1항"))
    else:
        out.append(_j("주택 임대", "면세", "상시주거용 건물과 부수토지의 임대. 주택 규모(국민주택 규모)와 관계없음", base + "제1항"))
    hf, fp, la, bf = (f.get(k) for k in ("house_floor_area", "building_footprint", "land_area", "business_floor_area"))
    nums = [x for x in (hf, fp, la, bf) if x is not None]
    if any(isinstance(x, bool) or not isinstance(x, (int, float)) or x < 0 for x in nums):
        return out + [_j("면적", "확인 필요", "면적은 0 이상의 숫자(㎡)", base)]
    ratio_land = 1.0
    if bf is not None and hf is not None:
        if hf > bf:
            out.append(_j("겸용주택", "면세", f"주택 부분 {hf:g}㎡가 사업용 건물 부분 {bf:g}㎡보다 커서 건물 전부를 주택 임대로 봄", base + mix_h + "제1호"))
        else:
            out.append(_j("겸용주택", "과세(사업용 건물 부분)", f"주택 부분 {hf:g}㎡가 사업용 건물 부분 {bf:g}㎡ 이하 — 사업용 건물 부분은 주택 임대로 보지 않고, 부수토지는 총토지면적 × 주택면적 비율", base + mix_h + "제2호"))
            ratio_land = hf / (hf + bf) if hf + bf else 0.0
    if hf is not None and fp is not None and la is not None:
        mult = 10 if f.get("outside_urban") else 5
        limit = max(hf, fp * mult)
        land = la * ratio_land
        if ratio_land < 1.0 and (land <= limit) != (land <= max(hf, fp * ratio_land * mult)):
            out.append(_j("부수토지", "확인 필요", f"주택 부분 부수토지 {land:g}㎡ — 정착면적 배율 한도를 건물 전체 정착면적({fp:g}㎡ × {mult}배 = {fp * mult:g}㎡)으로 보면 한도 안, "
                          f"주택 부분 비율로 나눈 정착면적으로 보면 한도 {max(hf, fp * ratio_land * mult):g}㎡를 넘음. {mix_h}제2호 '그 범위는 {lim_h}과 같다'의 적용 방식은 집행기준·해석례로 확인", base + mix_h + "제2호"))
        elif land <= limit:
            out.append(_j("부수토지", "면세", f"주택 부수토지 {land:g}㎡ ≤ 한도 {limit:g}㎡(주택 연면적 {hf:g}㎡와 정착면적 {fp:g}㎡ × {mult}배 중 넓은 면적)", base + lim_h))
        else:
            out.append(_j("부수토지", "일부 과세", f"부수토지 {land:g}㎡ 중 한도 {limit:g}㎡(주택 연면적과 정착면적 × {mult}배 중 넓은 면적)를 넘는 {land - limit:g}㎡는 토지의 임대로 봄", base + lim_h))
    elif la is not None:
        out.append(_j("부수토지", "확인 필요", "한도 계산에 house_floor_area와 building_footprint가 필요", base + lim_h))
    return out


