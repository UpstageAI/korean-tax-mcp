def _food(d, f):
    base = f"{_V} 제26조제1항제1호, {_R} 제34조"
    if f.get("edible") is False:
        if f.get("domestic") is True:
            return _j("미가공식료품", "면세", "우리나라에서 생산되어 식용으로 제공되지 않는 농·축·수·임산물(원생산물 또는 본래의 성상이 변하지 않는 원시가공)", base + "제3항")
        if f.get("domestic") is False:
            return _j("미가공식료품", "과세", "식용이 아닌 농·축·수·임산물은 우리나라에서 생산된 것만 면세", base + "제3항")
        return _j("미가공식료품", "확인 필요", "비식용이면 우리나라 생산 여부로 갈림(domestic)", base + "제3항")
