        if k in ("특허", "상표", "저작권"):
            J.append(_j(f"소득 구분({k})", "사용료", f"{k}권의 사용 대가 — 착수금·선불금, 침해 보상적 대가도 포함하고 등록 여부를 묻지 않음(통칙 93-132…6)",
                        "법인세법 제93조제8호 가목, 기본통칙 93-132…6" + (", 한미 조세조약 제14조(4)(a)" if us else ""), OK))
