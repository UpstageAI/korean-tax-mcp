def _treaty(country, lookup):
    """조약 조회 결과를 판정에 쓸 형태로. lookup(country) → ntis.withholding_rates(country, '사용료') 형식의 dict(없거나 실패하면 상태만)."""
    if not country:
        return {"상태": "미입력"}
    T = {"상태": "조회 안 함", "국가": country, "미국": country in ("미국", "미합중국", "USA", "US", "United States")}
    if T["미국"]: T["국가"] = "미국"
    if lookup is None:
        return T
    try:
        r = lookup(T["국가"])
    except Exception as e:   # 연결 실패 등 — 추정하지 않고 상태만 남김
        T["상태"] = "조회 실패"; T["오류"] = str(e)[:200]
        return T
    if not isinstance(r, dict) or r.get("error"):
        if isinstance(r, dict) and "체결국" in r:
            T["상태"] = "체결국 아님"
        else:
            T["상태"] = "조회 실패"; T["오류"] = str((r or {}).get("error", ""))[:200] if isinstance(r, dict) else ""
        return T
    T["상태"] = "조회함"; T["국가"] = r.get("국가", T["국가"]); T["미국"] = T["국가"] == "미국"
    T["발효일"] = r.get("발효일"); T["링크"] = r.get("링크")
    roy = next((x for x in r.get("제한세율") or [] if x.get("소득") == "사용료"), {}) or {}
    T["조문"] = roy.get("조문"); T["세율"] = roy.get("세율") or []; T["요건"] = [c for c in roy.get("요건·기타") or [] if c.get("구분")]
    T["개정 문서"] = roy.get("개정 문서 언급") or []
    lt = r.get("지방소득세") or {}
    T["지방세 포함"] = lt.get("대상조세 포함"); T["지방세 근거"] = lt.get("근거")
    src = next((c for c in T["요건"] if c["구분"] == "원천 규칙"), None)
    if src:
        t = src.get("근거", "")
        T["원천 조항"] = src.get("조항")
        T["원천 기준"] = "지급자" if re.search(r"payer", t, re.I) else ("사용지" if re.search(r"only if paid for the use", t, re.I) else None)
    return T


def _local_covered(T):
    if T.get("미국"): return False   # 한미 제1조: 한국의 경우 소득세 및 법인세(확인함)
    return T.get("지방세 포함")


def _rates(cap, covered, individual):
    """제한세율(또는 국내 세율) → 법인세율·지방소득세율·합계. 지방소득세 포함 조약은 법인세법 제98조의7제1항제2호(국내 세율 20%에 지방소득세를 반영한 22%와 비교)."""
    if individual or covered is None:
        return {"세율(%)": cap, "지방소득세율(%)": NEED, "합계(%)": NEED}
    if covered:
        tot = min(cap, 22.0)
        return {"법인세율(%)": round(tot / 1.1, 4), "지방소득세율(%)": round(tot / 11, 4), "합계(%)": tot, "지방소득세": "제한세율 안에 포함(법인세법 제98조의7제1항제2호)"}
    corp = min(cap, 20.0)
    return {"법인세율(%)": corp, "지방소득세율(%)": round(corp * 0.1, 4), "합계(%)": round(corp * 1.1, 4), "지방소득세": "제한세율과 따로(법인세법 제98조의7제1항제1호, 지방세법 제103조의52제1항)"}


