def _date(s):
    if isinstance(s, _dt.date): return s
    m = re.fullmatch(r"(\d{4})-?(\d{2})-?(\d{2})", str(s).strip())
    if not m: raise ValueError
    return _dt.date(int(m.group(1)), int(m.group(2)), int(m.group(3)))


