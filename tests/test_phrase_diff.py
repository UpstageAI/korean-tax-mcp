"""구절 대조 — 숫자·양태 신호 없이 낱말이 바뀌거나 자리가 뒤바뀐 진술을 '차이 없음'으로 넘기지 않음 (Claude 10-15).
조문 원문: 부가가치세법 시행령 제70조①1호, 국세기본법 제35조①3호사목 (법제처 시행본)."""
from korean_tax_mcp.claims import compare

VAT70 = [("제70조", "①", "", "① 법 제32조제7항에 따라 수정세금계산서 또는 수정전자세금계산서는 다음 각 호의 구분에 따른 사유 및 방법에 따라 발급할 수 있다."),
         ("제70조", "①", "1호", "1. 처음 공급한 재화가 환입(還入)된 경우: 재화가 환입된 날을 작성일로 적고 비고란에 처음 세금계산서 작성일을 덧붙여 적은 후 붉은색 글씨로 쓰거나 음(陰)의 표시를 하여 발급")]
NTS35 = [("제35조", "①", "3호", "3. 다음 각 목의 어느 하나에 해당하는 기일(이하 \"법정기일\"이라 한다) 전에 설정된 전세권"),
         ("제35조", "①", "3호사목", "사. 「국세징수법」 제31조제2항에 따라 납세자의 재산을 압류한 경우에 그 압류와 관련하여 확정된 세액에 대해서는 가목부터 마목까지의 규정에도 불구하고 그 압류등기일 또는 등록일")]


def test_swapped_phrases_not_no_difference():
    r = compare("처음 공급한 재화가 환입된 경우 재화를 처음 공급한 날을 작성일로 적고 비고란에 환입일을 덧붙여 적은 후 붉은색 글씨로 쓰거나 음(陰)의 표시를 하여 발급한다.", VAT70)
    assert r["판정"] == "구절 다름"
    pairs = {(d["진술"], d["조문"]) for d in r["대조"] if d["종류"] == "구절"}
    assert ("환입일을", "처음 세금계산서 작성일을") in pairs
    assert all(d["조문"] in VAT70[1][3] for d in r["대조"])        # 조문 쪽 구절은 원문 부분 문자열


def test_replaced_word_not_no_difference():
    r = compare("「국세징수법」에 따라 납세자의 재산을 압류한 경우에 그 압류와 관련하여 확정된 세액에 대해서는 그 납세의무의 확정일", NTS35)
    assert r["판정"] == "구절 다름"
    assert any("압류등기일" in d["조문"] and "확정일" in d["진술"] for d in r["대조"])


def test_same_meaning_stays_no_difference():
    r = compare("처음 공급한 재화가 환입된 경우에는 재화가 환입된 날을 작성일로 적고 비고란에 처음 세금계산서 작성일을 덧붙여 적은 후 붉은색 글씨로 쓰거나 음(陰)의 표시를 하여 발급한다.", VAT70)
    assert r["판정"] == "차이 없음"
