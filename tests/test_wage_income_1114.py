def test_foreign_flat_rate():
    f = lambda y, s, **k: G.guide(y, employee={"외국인": True, "최초근로일": s, **k})["외국인 단일세율"]
    # 세율 17%(2016) → 19%(2017년 발생분, 법률 제14390호 부칙)
    assert f(2016, "2015-03-01")["세율"] == "17%" and f(2017, "2015-03-01")["세율"] == "19%"
    # 근로 시작 기한: 2021년 시행본 2021.12.31., 2022년 시행본 2023.12.31.
    assert f(2021, "2022-01-01")["판정"] == "대상 아님"
    assert f(2022, "2022-01-01")["판정"] == "적용 가능"
    assert f(2024, "2026-12-31")["판정"] == "적용 가능"
    # 5년(2022년까지) → 20년(2023.1.1. 시행, 법률 제19199호 부칙)
    assert f(2021, "2017-03-01")["판정"] == "적용 가능"
    assert f(2022, "2017-03-01")["판정"] == "대상 아님"
    assert f(2023, "2017-03-01")["판정"] == "적용 가능"
