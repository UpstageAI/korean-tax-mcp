def test_invention_compensation_by_year():
    # 2016.12.31. 이전 지급분: 비과세 기타소득(법률 제14389호 부칙 경과조치) / 2017 300만, 2019 500만, 2024 700만(시행령 제17조의3)
    a = one(G.guide(payment_date="2016-12-31", items=[{"항목": "직무발명보상금", "연금액": 10_000_000}]))
    assert a["소득구분"] == "기타소득" and a["비과세(연)"] == 10_000_000
    caps = {y: one(G.guide(y, items=[{"항목": "직무발명보상금", "연금액": 10_000_000}]))["비과세(연)"] for y in (2017, 2018, 2019, 2023, 2024, 2026)}
    assert caps == {2017: 3_000_000, 2018: 3_000_000, 2019: 5_000_000, 2023: 5_000_000, 2024: 7_000_000, 2026: 7_000_000}
    assert one(G.guide(2024, items=[{"항목": "직무발명보상금", "연금액": 10_000_000}]))["소득구분"] == "근로소득"
    # 특수관계인 제외는 2024.1.1. 이후 지급분(법률 제19933호 부칙)
    assert one(G.guide(payment_date="2023-12-31", items=[{"항목": "직무발명보상금", "연금액": 1_000_000, "특수관계": True}]))["판정"] == "비과세"
    assert one(G.guide(payment_date="2024-01-01", items=[{"항목": "직무발명보상금", "연금액": 1_000_000, "특수관계": True}]))["판정"] == "과세"
    # 퇴직 후: 기타소득, 한도에서 같은 해 근로소득 비과세분 차감(시행령 제18조제2항)
    r = one(G.guide(2024, items=[{"항목": "직무발명보상금", "연금액": 5_000_000, "퇴직후": True, "같은해근로비과세": 3_000_000}]))
    assert r["소득구분"] == "기타소득" and (r["비과세(연)"], r["과세(연)"]) == (4_000_000, 1_000_000)


