def test_production_overtime_thresholds():
    def f(y, mw, pg, amt=3_000_000):
        return one(G.guide(y, items=[{"항목": "야간근로수당", "연금액": amt, "생산직직종": True, "월정액급여": mw, "직전연도총급여": pg}]))
    # 월정액급여 150만원(2017) → 190만원(2018) → 210만원(2019) → 260만원(2026)
    assert f(2017, 1_600_000, 20_000_000)["판정"] == "과세"
    assert f(2018, 1_600_000, 20_000_000)["비과세(연)"] == 2_400_000
    assert f(2018, 2_000_000, 20_000_000)["판정"] == "과세" and f(2019, 2_000_000, 20_000_000)["판정"] == "일부 과세"
    # 직전 과세기간 총급여 2,500만원 → 3천만원(2020) → 3,700만원(2026)
    assert f(2019, 2_000_000, 28_000_000)["판정"] == "과세" and f(2020, 2_000_000, 28_000_000)["판정"] == "일부 과세"
    assert f(2025, 2_500_000, 35_000_000)["판정"] == "과세" and f(2026, 2_500_000, 35_000_000)["판정"] == "일부 과세"
    r = f(2026, 2_600_000, 37_000_000)            # 기준과 같으면 '이하'
    assert (r["비과세(연)"], r["과세(연)"]) == (2_400_000, 600_000)
    m = one(G.guide(2024, items=[{"항목": "야간근로수당", "연금액": 5_000_000, "생산직직종": True, "광산일용": "광산"}]))
    assert m["비과세(연)"] == 5_000_000


