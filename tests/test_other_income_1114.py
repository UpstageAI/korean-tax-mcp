    assert J(O.guide("2018-12-31", "통신판매중개대여"))["시행 여부"]["판정"] == "해당 호 없음"
    assert J(O.guide("2019-01-01", "통신판매중개대여", 1_000_000))["필요경비"]["필요경비"] == "600,000원"
    assert J(O.guide("2019-01-01", "통신판매중개대여", facts={"annual_rent_8_2": 6_000_000}))["소득 구분"]["판정"] == "제8호의2 아님"
    # 무보수 위원 수당 비과세(제12조제5호자목) 2021.1.1.
    assert any(p["판정"] == "비과세 규정 없음(2020 이전)" for p in O.guide("2020-12-31", "일시적인적용역", facts={"unpaid_committee": True})["판정"])
    assert any(p["판정"] == "비과세" for p in O.guide("2021-01-01", "일시적인적용역", facts={"unpaid_committee": True})["판정"])
    # 가상자산: 2027.1.1. 이후 양도·대여분(세 차례 유예)
    v = O.guide("2026-12-31", "가상자산", 10_000_000)
