from korean_tax_mcp import other_income as O


def J(r):
    out = {}
    for p in r["판정"]:
        out.setdefault(p["항목"], p)
    return out


def test_overview_and_errors():
    o = O.guide()
    assert len(o["날짜에 따라 달라지는 것"]) == 11 and "일시적인적용역" in o["income_item 값"]
    assert "error" in O.guide("2015-12-31", "상금")
    assert "error" in O.guide("2027-01-01", "상금")
    assert "error" in O.guide("2024-13-01", "상금")
    assert "error" in O.guide("2024-01-01", "로또")
