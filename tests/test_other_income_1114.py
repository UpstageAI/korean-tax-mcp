    assert J(O.guide("2024-01-01", "직무발명보상금", facts={"retired": True, "employment_exempt_used": 2_000_000}))["비과세(제12조제5호라목)"]["판정"] == "연 5,000,000원까지 비과세"
    assert J(O.guide("2024-01-01", "직무발명보상금", facts={"retired": False}))["소득 구분"]["판정"] == "근로소득(재직 중 수령)"
