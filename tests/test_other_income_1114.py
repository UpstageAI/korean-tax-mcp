    assert J(O.guide("2017-01-01", "직무발명보상금", facts={"retired": True}))["비과세(제12조제5호라목)"]["판정"] == "연 3,000,000원까지 비과세"
    assert J(O.guide("2018-12-31", "직무발명보상금", facts={"retired": True}))["비과세(제12조제5호라목)"]["판정"] == "연 3,000,000원까지 비과세"
    assert J(O.guide("2019-01-01", "직무발명보상금", facts={"retired": True}))["비과세(제12조제5호라목)"]["판정"] == "연 5,000,000원까지 비과세"
    assert J(O.guide("2023-12-31", "직무발명보상금", facts={"retired": True, "related_party": True}))["비과세(제12조제5호라목)"]["판정"] == "연 5,000,000원까지 비과세"
